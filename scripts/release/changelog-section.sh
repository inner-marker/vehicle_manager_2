#!/usr/bin/env bash
# Prints one version's notes from CHANGELOG.md: the lines under its `## [x.y.z]`
# heading, up to the next `## [` heading or the footer's link references.
# Fails if the section is missing or empty. The release workflow uses this text as
# the GitHub Release notes, so the notes are exactly what was reviewed.
#
# Usage: scripts/release/changelog-section.sh <version> [changelog-file]
set -euo pipefail

if [ $# -lt 1 ]; then
    echo "usage: $0 <version> [changelog-file]" >&2
    exit 2
fi
version=$1
changelog=${2:-CHANGELOG.md}

if [ ! -f "$changelog" ]; then
    echo "error: $changelog not found" >&2
    exit 1
fi

# awk walks the file once:
# - a `## [<version>]` heading starts the section (the heading itself isn't printed);
# - the next `## [` heading, a `[x.y.z]: url` link line, or the generated-by marker ends it;
# - every line in between is printed.
section=$(awk -v heading="## [$version]" '
    index($0, heading) == 1 { in_section = 1; next }
    in_section && (/^## \[/ || /^\[[^]]+\]: / || /^<!-- generated by git-cliff -->/) { exit }
    in_section { print }
' "$changelog")

# A section with only blank lines counts as missing.
if [ -z "$(printf '%s' "$section" | tr -d '[:space:]')" ]; then
    echo "error: $changelog has no notes for version $version (expected a '## [$version]' section)" >&2
    exit 1
fi
printf '%s\n' "$section"
